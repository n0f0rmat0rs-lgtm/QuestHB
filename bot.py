# Нормализация: убираем лишние пробелы, приводим к верхнему регистру
def normalize(text: str) -> str:
    return " ".join(text.strip().upper().split())


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Привет! Введи кодовое слово, чтобы начать 🔑"
    )


async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_input = normalize(update.message.text)

    if user_input in MESSAGES:
        await update.message.reply_text(MESSAGES[user_input].strip())
    else:
        await update.message.reply_text(
            "Хм, не то слово. Попробуй ещё раз 🔍"
        )


def main():
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))
    print("Бот запущен!")
    app.run_polling(drop_pending_updates=True)


if __name__ == "__main__":
    main()
